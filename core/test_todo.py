#!/usr/bin/env python3
"""Proof that todo.py still agrees with the board.

The format is understood twice: in JavaScript in core/todo.js, which the board
loads, and in Python here in core/todo.py. Two copies of one set of rules is a
standing invitation to drift, and drift here is quiet — a meeting rolls to the
wrong Thursday and nothing complains.

It used to be three, the third being a hand-transcribed copy inside
pa-checkin/scripts/check_todo.py. That one is gone: the checker imports
core/todo.py from the repo, or the copy build.command stages beside it in the
zip. The JavaScript is the one that cannot import, because the board is a single
HTML file, so it is the one these tables exist to pin.

The tables are not in this file any more. They live in core/fixtures/ as JSON,
and core/test_todo.mjs reads the same three files and runs the same checks
against core/todo.js. Two suites, one set of answers — a table transcribed into
each language would be a third copy to keep in step, which is the problem this
is here to solve. Run both:

    python3 core/test_todo.py
    node core/test_todo.mjs

Every table was generated by running the board's own functions, so they hold the
board's answers rather than a second opinion.

  fixtures/repeat.json    thirty tag forms, each asked for its next occurrence
                          from seven days in each of fourteen months, and then
                          walked twelve occurrences from a fixed anchor. Between
                          them that covers month-end clamping, February, the nth
                          working day landing later in a short month, the
                          December rollover, and the `/n` intervals — which are
                          invisible to occurrenceFrom and only show up in a walk.
  fixtures/messages.json  the suggested-message notes, including curly quotes, a
                          colon inside the text, and a message written without
                          quotes at all.
  fixtures/parse.json     a task line carrying every tag, and the junk-input
                          edges where the two used to disagree: `****` as a
                          title, `rank:3px`, a numbered bucket below Context.
                          It pins what the board *writes* as well, which is the
                          one thing Python cannot check — todo.py has no
                          serialiser — so those columns are the JavaScript
                          suite's alone.

The calendar tables stay in this file, because there is nothing on the other
side to compare them against: the board has no working calendar and deliberately
never will. Those dates are worked out from the rules rather than typed in, which
is what stops the list expiring — and also what makes a quiet mistake possible,
since nothing complains if a rule is subtly wrong. The two tables below are the
published holidays for 2026 and 2027.

They were checked against the sources on 4 Sep 2026, and `--online` runs that
same check again: gov.uk's own feed for England and Wales, and Nager.Date for
Portugal, which has no official feed. Every England-and-Wales date from 2019 to
2028 agreed, apart from the five one-off events no rule can produce — the VE Day
move, the Jubilee, the State Funeral and the Coronation — which are written into
todo.UK_EXTRA and checked here too. Both Portuguese years agreed exactly.

The offline tables are what run by default. A test that needs the network is a
test that fails on a train.

    python3 core/test_todo.py             the pinned tables
    python3 core/test_todo.py --online    and again against the sources
"""

