SEED_DAYS = REPEAT["seedDays"]
SEED_MONTHS = REPEAT["seedMonths"]
START_YEAR = REPEAT["startYear"]
ANCHOR = dt.date.fromisoformat(REPEAT["anchor"])
# (tag, the label the board draws, its next occurrence from every seed date, and
# a run of twelve consecutive occurrences from the anchor).
# A label of None means the board rejects the tag, and so must this.
#
# The run is what tests an interval. One lives entirely in occurrence_after —
# occurrence_from answers "the next Wednesday", which has no phase to get wrong —
# so a fortnightly tag is indistinguishable from a weekly one until you walk a
# series. Twelve is enough to cross a year boundary on every form here.
CASES = [(c["tag"], c["label"], c["dates"], c["series"]) for c in REPEAT["cases"]]



